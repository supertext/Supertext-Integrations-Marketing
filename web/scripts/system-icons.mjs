// Writes src/lib/system-icons.js: the logos of the systems we integrate with, from Simple Icons
// (https://simpleicons.org, CC0; the logos stay their owners' trademarks and only name the system).
// Run: npm i --no-save simple-icons@16.37.0 && node scripts/system-icons.mjs
// Only systems listed here get a logo; the others keep their initials. Adobe, Microsoft, Salesforce,
// Slack and others aren't in Simple Icons (removed at the brands' request): don't add them by hand.
import * as icons from 'simple-icons';
import fs from 'node:fs';

/** Integration slug → Simple Icons slug. Only the system's own logo (django CMS isn't Django's). */
const SYSTEMS = {
  apostrophecms: 'apostrophe', contao: 'contao', 'craft-cms': 'craftcms', directus: 'directus', drupal: 'drupal',
  ghost: 'ghost', grav: 'grav', hubspot: 'hubspot', joomla: 'joomla', 'orchard-core': 'orchardcore',
  'payload-cms': 'payloadcms', strapi: 'strapi', typo3: 'typo3', umbraco: 'umbraco', wagtail: 'wagtail',
  'wordpress-polylang': 'wordpress', 'wordpress-wpml': 'wordpress', pimcore: 'pimcore', prestashop: 'prestashop',
  shopify: 'shopify', wix: 'wix', mailchimp: 'mailchimp', coreldraw: 'coreldraw', contentful: 'contentful',
  sanity: 'sanity', sitecore: 'sitecore', opentext: 'opentext', figma: 'figma', 'atlassian-confluence': 'confluence',
  'google-docs': 'googledocs', zendesk: 'zendesk', intercom: 'intercom', 'atlassian-jira': 'jira',
  'atlassian-trello': 'trello', notion: 'notion', github: 'github', gitlab: 'gitlab', 'atlassian-bitbucket': 'bitbucket',
  git: 'git', n8n: 'n8n', uipath: 'uipath', snowflake: 'snowflake', 'snowflake-cowork': 'snowflake',
  'google-cloud-looker': 'looker', 'google-gemini': 'googlegemini', 'mistral-ai': 'mistralai', 'meta-llama': 'meta',
};

const bySlug = new Map(Object.values(icons).filter((i) => i && i.slug).map((i) => [i.slug, i]));
const out = {};
for (const [slug, si] of Object.entries(SYSTEMS)) {
  const icon = bySlug.get(si);
  if (!icon) throw new Error(`Simple Icons has no "${si}" (for ${slug})`);
  out[slug] = { hex: icon.hex, path: icon.path };
}
const file = new URL('../src/lib/system-icons.js', import.meta.url);
fs.writeFileSync(file, `// Generated by scripts/system-icons.mjs from Simple Icons (CC0). Don't edit by hand.\nexport const SYSTEM_ICONS = ${JSON.stringify(out, null, 1)};\n`);
console.log(`${Object.keys(out).length} system icons written`);
